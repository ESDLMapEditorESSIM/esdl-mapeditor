import uuid
from datetime import datetime, timezone
from typing import TypedDict

from flask_socketio import SocketIO

from extensions.session_manager import get_session
import src.log as log
from flask import Flask, session

from extensions.settings_storage import SettingsStorage
from src.tno.live_model_interface.shared.message_types import AssetPositionMessage, Point

from src.tno.live_model_interface.shared.publisher import send_rabbitmq_message

logger = log.get_logger(__name__)


class MousePositionMessage(TypedDict):
    point: Point


class EventsAPI:
    """
    The EventsAPI is responsible for sending all events that are generated by the frontend to external live model
    interfaces over RabbitMQ.
    """
    def __init__(
        self, flask_app: Flask, socket: SocketIO, settings_storage: SettingsStorage
    ):
        self.flask_app = flask_app
        self.socketio = socket
        self.register()

    def register(self):
        logger.info("Registering EventsAPI")

        @self.socketio.on("events.asset.positioning", namespace="/esdl")
        def mouse_positioning(frontend_message: MousePositionMessage):
            logger.info("Positioning asset", message=frontend_message)
            user_email = get_session('user-email')
            client_id = session['client_id']
            message: AssetPositionMessage = dict(
                **frontend_message,
                user_email=user_email,
                client_id=client_id,
                id=str(uuid.uuid4()),
                timestamp=datetime.now(timezone.utc),
            )
            # rabbitmq_fanout_publisher.publish_message(message)
            send_rabbitmq_message(message, "events.asset.positioning")
